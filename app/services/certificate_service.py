"""Looking up certificates and locating their files for download."""

import logging
import uuid
from pathlib import Path

from sqlalchemy.orm import Session

from app.core.errors import CertificateFileUnavailableError, ConflictError, NotFoundError
from app.db.models import Certificate, CertificateStatus

logger = logging.getLogger(__name__)


def get_certificate(session: Session, certificate_id: uuid.UUID) -> Certificate:
    certificate = session.get(Certificate, certificate_id)
    if certificate is None:
        raise NotFoundError("Certificate not found")
    return certificate


def get_certificate_file(certificate: Certificate, output_dir: Path) -> Path:
    """Return the absolute path of a COMPLETED certificate's PDF.

    Raises ConflictError (409) when the certificate failed or is not generated yet.
    """
    if certificate.status == CertificateStatus.FAILED:
        raise ConflictError(
            "Certificate generation failed, so there is no file to download",
            code="certificate_generation_failed",
        )
    if certificate.status != CertificateStatus.COMPLETED or certificate.file_path is None:
        raise ConflictError(
            "Certificate has not been generated yet", code="certificate_not_ready"
        )

    base_dir = output_dir.resolve()
    path = (base_dir / certificate.file_path).resolve()
    # Defence in depth: file_path is generated by us, but never serve anything outside OUTPUT_DIR.
    if not path.is_relative_to(base_dir) or not path.is_file():
        logger.error(
            "Certificate file missing or outside output directory certificate_id=%s",
            certificate.id,
        )
        raise CertificateFileUnavailableError("Certificate file is currently unavailable")
    return path
